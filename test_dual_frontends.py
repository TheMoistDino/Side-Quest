def test_frontend_ingestion_path():
    """Verify Path A: Ingests raw FrontendQuestRequest into QuestConstraints."""
    print("Testing Path A: Frontend Ingestion & Normalization...")

    # Exact payload generated by components/wizard/answers.ts -> toQuestRequest(answers)
    now = datetime.now(timezone.utc)
    start_iso = (now + timedelta(hours=1)).isoformat()
    end_iso = (now + timedelta(hours=4)).isoformat()

    req = FrontendQuestRequest(
        category="food",
        startTime=start_iso,
        endTime=end_iso,
        budgetPerPerson=40.0,
        maxDistanceMiles=10.0,
        location=FrontendLocation(
            lat=34.0635,
            lng=-118.4455,
            label="Westwood, Los Angeles",
        ),
        groupSize=2,
    )

    constraints = adapt_frontend_request_to_constraints(req)

    assert constraints.duration_minutes == 180, f"Expected 180 mins, got {constraints.duration_minutes}"
    assert constraints.budget_usd == 40.0, f"Expected $40.0, got {constraints.budget_usd}"
    assert "Westwood" in constraints.origin, f"Expected Westwood in origin, got {constraints.origin}"
    assert constraints.vibe == "food", f"Expected 'food' vibe, got {constraints.vibe}"
    assert constraints.departure_time is not None
    assert constraints.return_cutoff is not None
    print("  [PASS] Standard QuestRequest accurately mapped to QuestConstraints.")

    # Edge cases: missing label, "outdoors", "surprise me", negative budget
    edge_req = FrontendQuestRequest(
        category="outdoors",
        startTime=start_iso,
        endTime=end_iso,
        budgetPerPerson=-5.0,
        maxDistanceMiles=5.0,
        location=FrontendLocation(lat=34.0195, lng=-118.4912, label=None),
        groupSize=1,
    )
    edge_constraints = adapt_frontend_request_to_constraints(edge_req)
    assert edge_constraints.vibe == "chill", f"Expected outdoors -> chill, got {edge_constraints.vibe}"
    assert "Santa Monica" in edge_constraints.origin, f"Expected nearest neighborhood Santa Monica, got {edge_constraints.origin}"
    assert edge_constraints.budget_usd == 35.0, f"Expected fallback budget $35, got {edge_constraints.budget_usd}"
    print("  [PASS] Edge cases (category mapping, nearest neighborhood resolution, budget fallback) handled gracefully.")


