function addMinutes(iso: string, minutes: number): string {
  return new Date(new Date(iso).getTime() + minutes * 60_000).toISOString();
}

export function buildMockResponse(req: QuestRequest): QuestResponse {
  return {
    quests: MOCK_QUESTS.map(({ stops, ...quest }) => ({
      ...quest,
      stops: stops.map(({ offsetMinutes, ...stop }) => ({
        ...stop,
        startTime: addMinutes(req.startTime, offsetMinutes),
      })),
    })),
  };
}
